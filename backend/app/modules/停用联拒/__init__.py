"""骨签 hook-12-停用端点联拒。

领域规则（本 hook 主体，不是数据采集、不是工单客服）：

1. 端点名册启用灯为「停用」的端点，一律拒绝正式入队。
2. 启用灯联查与入队写入同成同败（见 :mod:`app.modules.并发投递锁`）。
3. 选边的工程形态为「双写两轨」：停用端被拒的入队进**只读归档轨**
   （表 ``停用归档``），现行队列只读**启用端点集合**，下游读集合可分开。
4. 同时在 ``端点凭证`` 表钉一枚「启用指纹」作为同票令牌，并拒绝对停用端点
   做「回刷成启用指纹」（拒停用回刷）。
5. 对账把跨表联查得到的停用端在队行单列为「影子挂账」，不得混进正式集合，
   且停用灯亮仍有入队时判对账撕裂/非法。
"""
from __future__ import annotations

import hashlib

骨签 = "hook-12-停用端点联拒"

启用中文 = {1: "启用", 0: "停用", True: "启用", False: "停用"}


def 启用灯(值) -> str:
    try:
        return "启用" if int(值) == 1 else "停用"
    except (TypeError, ValueError):
        return "停用"


def 启用指纹(端点键: str, 启用, 密钥版本: str = "v1", 版本号: int = 1) -> str:
    """钉在凭证表 / 事件上的启用指纹。

    指纹把「端点键 + 当前启用灯 + 密钥版本 + 凭证版本」绑在一起；停用后
    启用位为 0，无法再冒充启用指纹。
    """
    灯 = 1 if int(启用) == 1 else 0
    raw = f"{骨签}|{端点键}|启用={灯}|{密钥版本 or 'v1'}|v{版本号}".encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:32]


def 拒因中文(端点键: str) -> str:
    return (
        f"端点「{端点键}」名册启用灯为停用，停用联拒：拒绝写入正式待投队列，"
        f"该次入队已转入只读归档轨并记录拒因。（{骨签}）"
    )


class 停用联拒错误(ValueError):
    """停用端点入队被联拒；携带可直接上页的中文载荷。"""

    def __init__(self, 拒因: str, 端点键: str = "", 归档号: str = ""):
        super().__init__(拒因)
        self.拒因 = 拒因
        self.端点键 = 端点键
        self.归档号 = 归档号

    def 载荷(self) -> dict:
        return {
            "ok": False,
            "入队成败": False,
            "错误": self.拒因,
            "拒因": self.拒因,
            "端点键": self.端点键,
            "启用灯": "停用",
            "归档号": self.归档号,
            "骨签": 骨签,
        }
