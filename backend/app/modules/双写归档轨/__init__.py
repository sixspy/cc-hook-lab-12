"""空桩→实装：双写两轨之「只读归档轨」（骨签 hook-12-停用端点联拒）。

选边结论：采用双写两轨。

- 正式轨：表 ``事件``，只接收启用端点的事件，现行队列读启用端点集合。
- 归档轨：表 ``停用归档``，停用端被联拒的入队尝试写这里，**只读**留痕，
  携带 ``入队成败=0`` 与中文 ``拒因``，供事件队列卡片/归档区直接读取。

本模块只提供归档轨的写入与只读查询辅助，不反向影响正式集合。
"""
from __future__ import annotations

import uuid

NAME = "双写归档轨"
归档表 = "停用归档"


def 写归档(
    conn,
    *,
    端点键: str,
    拒因: str,
    时刻: str,
    事件号: str = "",
    事件类型: str = "",
    载荷摘要: str = "",
    优先级: str = "普通",
    启用指纹值: str = "",
) -> str:
    """在调用方的同票事务内写一条只读归档，返回归档号。"""
    归档号 = f"ARC-{uuid.uuid4().hex[:12]}"
    conn.execute(
        "INSERT INTO 停用归档("
        "归档号,时刻,事件号,事件类型,端点键,载荷摘要,优先级,入队成败,拒因,启用指纹"
        ") VALUES (?,?,?,?,?,?,?,0,?,?)",
        (
            归档号, 时刻, 事件号, 事件类型, 端点键, 载荷摘要, 优先级,
            拒因, 启用指纹值,
        ),
    )
    return 归档号


def 列归档(conn, 限制: int = 200):
    return [
        dict(r)
        for r in conn.execute(
            "SELECT * FROM 停用归档 ORDER BY 时刻 DESC, 归档号 DESC LIMIT ?",
            (限制,),
        ).fetchall()
    ]
